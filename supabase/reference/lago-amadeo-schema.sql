CREATE OR REPLACE FUNCTION public.fn_actualizar_cuotas_concepto()
 RETURNS trigger
 LANGUAGE plpgsql
AS $function$
declare
  v_importe numeric;
begin

  -- Obtener el importe del nuevo concepto
  select cp.importe
  into v_importe
  from conceptos_pago cp
  where cp.id = new.concepto_id;

  -- Actualizar cuotas pendientes del domicilio
  update cuotas
  set
    concepto_id = new.concepto_id,
    importe = v_importe
  where domicilio_id = new.domicilio_id
    and estatus_id = 1;

  return new;
end;
$function$
;

CREATE OR REPLACE FUNCTION public.fn_pago_to_movimiento()
 RETURNS trigger
 LANGUAGE plpgsql
AS $function$
begin
  -- 👇 no crear movimiento si el importe es 0
  if coalesce(new.importe, 0) = 0 then
    return new;
  end if;

  insert into public.movimientos_financieros (
    tipo_id,
    descripcion,
    importe,
    metodo_pago_id,
    referencia,
    user_id,
    fecha_movimiento
  )
  values (
    1,
    'Pago referencia:  ' || new.referencia,
    new.importe,
    new.metodo_pago_id,
    new.referencia,
    new.user_id,
    new.fecha_pago
  );

  return new;
end;
$function$
;

CREATE OR REPLACE FUNCTION public.fn_residente_principal()
 RETURNS trigger
 LANGUAGE plpgsql
AS $function$
declare
  total_residentes integer;
begin
  -- Normalizar NULL a false
  if new.es_principal is null then
    new.es_principal := false;
  end if;

  -- Contar residentes existentes
  select count(*) into total_residentes
  from public.residentes
  where domicilio_id = new.domicilio_id
  and (tg_op = 'INSERT' or id <> new.id);

  -- Primer residente → automático principal
  if total_residentes = 0 then
    new.es_principal := true;
    return new;
  end if;

  -- Si viene como principal → quitar a los demás
  if new.es_principal = true then
    update public.residentes
    set es_principal = false
    where domicilio_id = new.domicilio_id
    and id <> coalesce(new.id, -1);
  end if;

  return new;
end;
$function$
;

CREATE OR REPLACE FUNCTION public.generar_cuotas(p_anio integer, p_mes integer)
 RETURNS void
 LANGUAGE sql
AS $function$
  insert into cuotas (
    domicilio_id,
    anio,
    mes,
    fecha_vencimiento,
    estatus_id,
    concepto_id,
    importe
  )
  select
    dc.domicilio_id,
    p_anio,
    p_mes,
    (make_date(p_anio, p_mes, 1) + interval '1 month - 1 day')::date,
    1,
    dc.concepto_id,
    cp.importe

  from domicilio_concepto dc
  join conceptos_pago cp on cp.id = dc.concepto_id

  where not exists (
    select 1
    from cuotas c
    where c.domicilio_id = dc.domicilio_id
      and c.concepto_id = dc.concepto_id
      and c.anio = p_anio
      and c.mes = p_mes
  );
$function$
;

CREATE OR REPLACE FUNCTION public.marcar_cuotas_vencidas()
 RETURNS void
 LANGUAGE plpgsql
AS $function$
begin
  update public.cuotas c
  set estatus_id = 3
  where c.fecha_vencimiento < current_date
    and c.estatus_id != 3 -- evita reprocesar
    and not exists (
      select 1
      from public.pagos p
      where p.cuota_id = c.id
    );
end;
$function$
;


