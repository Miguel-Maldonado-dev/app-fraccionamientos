-- Núcleo multi-tenant: fraccionamientos, perfiles, funciones de apoyo y políticas.

create type public.rol_usuario as enum ('super_admin', 'administrador', 'tesorero', 'comite', 'vigilancia');

-- Fraccionamientos ---------------------------------------------------------

create table public.fraccionamientos (
  id bigint generated by default as identity not null,
  nombre text not null,
  slug text not null,
  -- Id de la instalación de Access Core (integración futura). Opcional.
  instalacion_id uuid,
  activo boolean not null default true,
  created_at timestamp with time zone not null default now(),
  constraint fraccionamientos_pkey primary key (id),
  constraint fraccionamientos_slug_key unique (slug),
  constraint fraccionamientos_instalacion_id_key unique (instalacion_id),
  constraint fraccionamientos_slug_check check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$')
);

-- Perfiles -----------------------------------------------------------------

create table public.perfiles (
  id uuid not null,
  fraccionamiento_id bigint,
  rol public.rol_usuario not null,
  nombre text not null,
  email text not null,
  activo boolean not null default true,
  created_at timestamp with time zone not null default now(),
  constraint perfiles_pkey primary key (id),
  constraint perfiles_id_fkey foreign key (id) references auth.users (id) on delete cascade,
  constraint perfiles_fraccionamiento_id_fkey foreign key (fraccionamiento_id)
    references public.fraccionamientos (id),
  -- Solo el super admin vive fuera de un fraccionamiento.
  constraint perfiles_rol_fraccionamiento_check
    check ((rol = 'super_admin') = (fraccionamiento_id is null))
);

create index perfiles_fraccionamiento_id_idx on public.perfiles (fraccionamiento_id);

-- Funciones de apoyo (esquema privado, no expuesto por la API) -------------
-- security definer: leen perfiles sin pasar por su RLS (evita recursión).
-- Solo consideran el perfil de auth.uid() activo y, salvo super admin, con
-- su fraccionamiento activo.

create schema if not exists private;

create function private.fraccionamiento_actual()
returns bigint
language sql
stable
security definer
set search_path = ''
as $$
  select p.fraccionamiento_id
  from public.perfiles p
  join public.fraccionamientos f on f.id = p.fraccionamiento_id
  where p.id = (select auth.uid())
    and p.activo
    and f.activo;
$$;

create function private.rol_actual()
returns public.rol_usuario
language sql
stable
security definer
set search_path = ''
as $$
  select p.rol
  from public.perfiles p
  left join public.fraccionamientos f on f.id = p.fraccionamiento_id
  where p.id = (select auth.uid())
    and p.activo
    and (p.rol = 'super_admin' or f.activo);
$$;

create function private.es_super_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce((select private.rol_actual()) = 'super_admin', false);
$$;

create function private.tiene_rol(roles public.rol_usuario[])
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce((select private.rol_actual()) = any (roles), false);
$$;

revoke all on schema private from public, anon;
grant usage on schema private to authenticated, service_role;

revoke execute on function
  private.fraccionamiento_actual(),
  private.rol_actual(),
  private.es_super_admin(),
  private.tiene_rol(public.rol_usuario[])
from public, anon;

grant execute on function
  private.fraccionamiento_actual(),
  private.rol_actual(),
  private.es_super_admin(),
  private.tiene_rol(public.rol_usuario[])
to authenticated, service_role;

-- RLS: fraccionamientos ----------------------------------------------------

alter table public.fraccionamientos enable row level security;

create policy fraccionamientos_select on public.fraccionamientos
  for select to authenticated
  using (
    id = (select private.fraccionamiento_actual())
    or (select private.es_super_admin())
  );

create policy fraccionamientos_insert on public.fraccionamientos
  for insert to authenticated
  with check ((select private.es_super_admin()));

create policy fraccionamientos_update on public.fraccionamientos
  for update to authenticated
  using ((select private.es_super_admin()))
  with check ((select private.es_super_admin()));

create policy fraccionamientos_delete on public.fraccionamientos
  for delete to authenticated
  using ((select private.es_super_admin()));

-- Los privilegios por defecto del esquema public dan a anon y authenticated
-- TRUNCATE, REFERENCES, TRIGGER y MAINTAIN (TRUNCATE ignora RLS). Se quitan
-- y se otorga solo lo necesario.
revoke all on public.fraccionamientos from anon, authenticated;
revoke all on sequence public.fraccionamientos_id_seq from anon, authenticated;
grant select, insert, update, delete on public.fraccionamientos to authenticated;
grant all on public.fraccionamientos to service_role;

-- RLS: perfiles ------------------------------------------------------------

alter table public.perfiles enable row level security;

create policy perfiles_select on public.perfiles
  for select to authenticated
  using (
    id = (select auth.uid())
    or (select private.es_super_admin())
    -- Cualquier rol activo de un fraccionamiento activo ve los perfiles de su
    -- fraccionamiento (reportes de pagos por usuario, users_info).
    or fraccionamiento_id = (select private.fraccionamiento_actual())
  );

create policy perfiles_insert on public.perfiles
  for insert to authenticated
  with check (
    (select private.es_super_admin())
    or (
      (select private.tiene_rol(array['administrador']::public.rol_usuario[]))
      and fraccionamiento_id = (select private.fraccionamiento_actual())
      and rol <> 'super_admin'
    )
  );

create policy perfiles_update on public.perfiles
  for update to authenticated
  using (
    (select private.es_super_admin())
    or (
      (select private.tiene_rol(array['administrador']::public.rol_usuario[]))
      and fraccionamiento_id = (select private.fraccionamiento_actual())
      and rol <> 'super_admin'
    )
  )
  with check (
    (select private.es_super_admin())
    or (
      (select private.tiene_rol(array['administrador']::public.rol_usuario[]))
      and fraccionamiento_id = (select private.fraccionamiento_actual())
      and rol <> 'super_admin'
    )
  );

create policy perfiles_delete on public.perfiles
  for delete to authenticated
  using ((select private.es_super_admin()));

revoke all on public.perfiles from anon, authenticated;
grant select, insert, update, delete on public.perfiles to authenticated;
grant all on public.perfiles to service_role;
