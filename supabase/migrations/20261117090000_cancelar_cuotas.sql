-- Cancelar cuotas (spec 2026-11-13-cancelar-cuotas). Estatus 4 'Cancelado':
-- no se cobra, no cuenta para morosidad, no se puede pagar; se puede reactivar.
-- El proceso diario (actualizar_estatus_cuotas, recargos) y es_moroso ya solo
-- miran estatus 1/3, así que una cuota cancelada queda fuera sin cambiarlos.

insert into public.estatus (id, name) overriding system value values (4, 'Cancelado');

-- Columnas de cancelación: presentes si y solo si estatus 4 ------------------------

alter table public.cuotas
  add column cancelada_en timestamptz,
  add column cancelada_por uuid,
  add column motivo_cancelacion text,
  add constraint cuotas_cancelacion_check check (
    (estatus_id = 4) = (cancelada_en is not null and motivo_cancelacion is not null)
    and (estatus_id = 4 or (cancelada_por is null and motivo_cancelacion is null))
  );

-- authenticated no escribe las columnas de cancelación: solo las RPC. Con el
-- check, tampoco puede poner ni quitar el estatus 4 directamente.
revoke insert, update on public.cuotas from authenticated;
grant insert (
  id, created_at, fraccionamiento_id, domicilio_id, anio, mes, fecha_vencimiento, estatus_id, concepto_id, importe
) on public.cuotas to authenticated;
grant update (
  id, created_at, fraccionamiento_id, domicilio_id, anio, mes, fecha_vencimiento, estatus_id, concepto_id, importe
) on public.cuotas to authenticated;

-- Historial ----------------------------------------------------------------------------

create table public.cuotas_cancelaciones (
  id bigint generated by default as identity primary key,
  fraccionamiento_id bigint not null references public.fraccionamientos (id) on delete cascade,
  cuota_id bigint not null,
  accion text not null,
  motivo text,
  usuario_id uuid,
  created_at timestamptz not null default now(),
  constraint cuotas_cancelaciones_accion_check check (accion in ('cancelar', 'reactivar')),
  constraint cuotas_cancelaciones_cuota_id_fkey foreign key (cuota_id, fraccionamiento_id)
    references public.cuotas (id, fraccionamiento_id) on delete cascade
);
alter table public.cuotas_cancelaciones enable row level security;
create index cuotas_cancelaciones_cuota_id_fracc_idx on public.cuotas_cancelaciones (cuota_id, fraccionamiento_id);
create index cuotas_cancelaciones_fraccionamiento_id_idx on public.cuotas_cancelaciones (fraccionamiento_id);

create policy cuotas_cancelaciones_select on public.cuotas_cancelaciones
  for select to authenticated
  using (
    (select private.es_super_admin())
    or (fraccionamiento_id = (select private.fraccionamiento_actual())
        and (select private.tiene_rol(array['administrador', 'tesorero']::public.rol_usuario[])))
  );

-- Sin políticas de escritura: solo las RPC (security definer) insertan.
revoke all on public.cuotas_cancelaciones from anon, authenticated;
grant select on public.cuotas_cancelaciones to authenticated;
grant all on public.cuotas_cancelaciones to service_role;

-- Cancelar ------------------------------------------------------------------------------
-- Todo o nada: cuotas del fraccionamiento actual, de un mismo domicilio, sin
-- pago y no canceladas ni pagadas. Solo administrador.

create function private.cancelar_cuotas(p_cuota_ids bigint[], p_motivo text)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_fid bigint := (select private.fraccionamiento_actual());
  v_motivo text := btrim(coalesce(p_motivo, ''));
  v_ids bigint[];
  v_n integer;
  v_doms integer;
  v_dom bigint;
begin
  if v_fid is null
     or (select private.es_super_admin())
     or not (select private.tiene_rol(array['administrador']::public.rol_usuario[])) then
    raise exception 'No tienes permiso para cancelar cuotas' using errcode = '42501';
  end if;

  if char_length(v_motivo) < 3 or char_length(v_motivo) > 500 then
    raise exception 'El motivo debe tener entre 3 y 500 caracteres' using errcode = '22023';
  end if;

  select array_agg(distinct x) into v_ids from unnest(p_cuota_ids) as x where x is not null;
  if coalesce(cardinality(v_ids), 0) = 0 then
    raise exception 'Selecciona al menos una cuota' using errcode = '22023';
  end if;

  -- Bloquea las filas para que un pago concurrente no se cuele.
  perform 1 from public.cuotas c where c.id = any (v_ids) and c.fraccionamiento_id = v_fid order by c.id for update;

  select count(*), count(distinct c.domicilio_id), min(c.domicilio_id) into v_n, v_doms, v_dom
  from public.cuotas c
  where c.id = any (v_ids) and c.fraccionamiento_id = v_fid;

  if v_n <> cardinality(v_ids) then
    raise exception 'Alguna cuota no existe o no pertenece al fraccionamiento' using errcode = 'P0001';
  end if;
  if v_doms <> 1 then
    raise exception 'Las cuotas deben ser de un mismo domicilio' using errcode = 'P0001';
  end if;
  if exists (
    select 1 from public.cuotas c
    where c.id = any (v_ids)
      and (c.estatus_id not in (1, 3) or exists (select 1 from public.pagos p where p.cuota_id = c.id))
  ) then
    raise exception 'Solo se pueden cancelar cuotas sin pago y no canceladas' using errcode = 'P0001';
  end if;

  update public.cuotas c
  set estatus_id = 4,
      cancelada_en = now(),
      cancelada_por = (select auth.uid()),
      motivo_cancelacion = v_motivo
  where c.id = any (v_ids);

  insert into public.cuotas_cancelaciones (fraccionamiento_id, cuota_id, accion, motivo, usuario_id)
  select v_fid, x, 'cancelar', v_motivo, (select auth.uid()) from unnest(v_ids) as x;

  -- Encola la resincronización si cambia el perfil deseado del domicilio.
  perform public.recalcular_permisos_acceso(v_fid);

  return v_n;
end;
$$;

create function public.cancelar_cuotas(p_cuota_ids bigint[], p_motivo text)
returns integer
language sql
security invoker
set search_path = ''
as $$
  select private.cancelar_cuotas(p_cuota_ids, p_motivo);
$$;

-- Reactivar -------------------------------------------------------------------------------
-- Recalcula el estatus (Pendiente / Vencida con días de gracia); recargos y
-- descuentos quedan como estaban.

create function private.reactivar_cuota(p_cuota_id bigint)
returns smallint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_fid bigint := (select private.fraccionamiento_actual());
  v_cuota record;
  v_gracia integer;
  v_estatus smallint;
begin
  if v_fid is null
     or (select private.es_super_admin())
     or not (select private.tiene_rol(array['administrador']::public.rol_usuario[])) then
    raise exception 'No tienes permiso para reactivar cuotas' using errcode = '42501';
  end if;

  select c.id, c.estatus_id, c.fecha_vencimiento into v_cuota
  from public.cuotas c
  where c.id = p_cuota_id and c.fraccionamiento_id = v_fid
  for update;

  if v_cuota.id is null then
    raise exception 'La cuota no existe' using errcode = 'P0001';
  end if;
  if v_cuota.estatus_id <> 4 then
    raise exception 'La cuota no está cancelada' using errcode = 'P0001';
  end if;

  v_gracia := coalesce((select r.dias_gracia from private.reglas_de(v_fid) r), 0);
  v_estatus := case when v_cuota.fecha_vencimiento + v_gracia < private.hoy() then 3 else 1 end;

  update public.cuotas c
  set estatus_id = v_estatus, cancelada_en = null, cancelada_por = null, motivo_cancelacion = null
  where c.id = p_cuota_id;

  insert into public.cuotas_cancelaciones (fraccionamiento_id, cuota_id, accion, motivo, usuario_id)
  values (v_fid, p_cuota_id, 'reactivar', null, (select auth.uid()));

  perform public.recalcular_permisos_acceso(v_fid);

  return v_estatus;
end;
$$;

create function public.reactivar_cuota(p_cuota_id bigint)
returns smallint
language sql
security invoker
set search_path = ''
as $$
  select private.reactivar_cuota(p_cuota_id);
$$;

-- Pagos: una cuota cancelada no se puede pagar (guard en el insert de pagos,
-- el camino que usa la acción registrarPagoCuota).

create function private.fn_pagos_cuota_no_cancelada()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  -- FOR SHARE serializa contra el FOR UPDATE de cancelar_cuotas.
  if new.cuota_id is not null
     and (select c.estatus_id from public.cuotas c where c.id = new.cuota_id for share) = 4 then
    raise exception 'La cuota está cancelada y no se puede pagar' using errcode = 'P0001';
  end if;
  return new;
end;
$$;

create trigger trg_pagos_cuota_no_cancelada
  before insert or update of cuota_id on public.pagos
  for each row execute function private.fn_pagos_cuota_no_cancelada();

