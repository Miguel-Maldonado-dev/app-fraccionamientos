-- Moroso efectivo ----------------------------------------------------------------
-- La misma regla de perfil_deseado: el ajuste manual (acceso_forzado) gana
-- sobre el cálculo por cuotas vencidas.

create function private.moroso_efectivo(p_domicilio_id bigint)
returns boolean
language sql
stable
security invoker
set search_path = ''
as $$
  select case
           when d.acceso_forzado = 'activo' then false
           when d.acceso_forzado = 'inactivo' then true
           else coalesce(private.es_moroso(d.id), false)
         end
  from public.domicilios d
  where d.id = p_domicilio_id;
$$;

create or replace function public.perfil_deseado(p_domicilio_id bigint)
returns uuid
language sql
stable
security invoker
set search_path = ''
as $$
  select case
           when coalesce(private.moroso_efectivo(d.id), false) then cpa.perfil_moroso_id
           else cpa.perfil_corriente_id
         end
  from public.domicilios d
  join public.domicilio_concepto dc on dc.domicilio_id = d.id
  join public.concepto_pago_acceso cpa on cpa.concepto_pago_id = dc.concepto_id
  where d.id = p_domicilio_id;
$$;

-- app_botones ------------------------------------------------------------------------

create table public.app_botones (
  id bigint generated by default as identity primary key,
  fraccionamiento_id bigint not null references public.fraccionamientos (id) on delete cascade,
  orden smallint not null,
  nombre text not null,
  icono text not null default 'puerta',
  ancho_completo boolean not null default false,
  salida_id uuid,
  salida_nombre text,
  created_at timestamptz not null default now(),
  constraint app_botones_orden_check check (orden between 1 and 8),
  constraint app_botones_nombre_check check (char_length(nombre) between 1 and 30),
  constraint app_botones_icono_check check (
    icono in ('puerta', 'pluma', 'peatonal', 'vehiculo', 'alberca', 'gimnasio', 'salon', 'otro')
  ),
  constraint app_botones_fraccionamiento_orden_key unique (fraccionamiento_id, orden)
);
alter table public.app_botones enable row level security;

-- Máximo 8 botones por fraccionamiento.
create function private.fn_app_botones_maximo()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if (select count(*) from public.app_botones b
      where b.fraccionamiento_id = new.fraccionamiento_id and b.id <> new.id) >= 8 then
    raise exception 'Máximo 8 botones por fraccionamiento' using errcode = '23514';
  end if;
  return new;
end;
$$;

create trigger trg_app_botones_maximo
  before insert or update of fraccionamiento_id on public.app_botones
  for each row execute function private.fn_app_botones_maximo();

create policy app_botones_select on public.app_botones
  for select to authenticated
  using (
    (select private.es_super_admin())
    or fraccionamiento_id = (select private.fraccionamiento_actual())
    or fraccionamiento_id in (
      select d.fraccionamiento_id from public.domicilios d
      where d.id in (select private.domicilios_del_residente())
    )
  );

create policy app_botones_insert on public.app_botones
  for insert to authenticated
  with check ((select private.es_super_admin()));

create policy app_botones_update on public.app_botones
  for update to authenticated
  using ((select private.es_super_admin()))
  with check ((select private.es_super_admin()));

create policy app_botones_delete on public.app_botones
  for delete to authenticated
  using ((select private.es_super_admin()));

revoke all on public.app_botones from anon, authenticated;
grant select, insert, update, delete on public.app_botones to authenticated;
grant all on public.app_botones to service_role;

-- Al cambiar la instalación las salidas dejan de existir: botones "sin salida".
-- Trigger AFTER: corre solo si fn_fraccionamientos_solo_max (BEFORE) lo permitió.
create function private.fn_fraccionamientos_limpiar_salidas()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  update public.app_botones
  set salida_id = null, salida_nombre = null
  where fraccionamiento_id = new.id
    and (salida_id is not null or salida_nombre is not null);
  return null;
end;
$$;

create trigger trg_fraccionamientos_limpiar_salidas
  after update of instalacion_id on public.fraccionamientos
  for each row
  when (old.instalacion_id is distinct from new.instalacion_id)
  execute function private.fn_fraccionamientos_limpiar_salidas();

-- aperturas_remotas ----------------------------------------------------------------------

create table public.aperturas_remotas (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  fraccionamiento_id bigint not null references public.fraccionamientos (id) on delete cascade,
  domicilio_id bigint not null,
  boton_id bigint,
  user_id uuid not null,
  resultado text not null,
  detalle text,
  constraint aperturas_remotas_resultado_check check (
    resultado in ('opened', 'denied', 'failed', 'timeout', 'moroso', 'no_disponible', 'limite', 'error')
  )
);
alter table public.aperturas_remotas enable row level security;
create index aperturas_remotas_user_id_created_at_idx on public.aperturas_remotas (user_id, created_at);
create index aperturas_remotas_fraccionamiento_id_idx on public.aperturas_remotas (fraccionamiento_id);

create policy aperturas_remotas_select on public.aperturas_remotas
  for select to authenticated
  using (
    (select private.es_super_admin())
    or (
      fraccionamiento_id = (select private.fraccionamiento_actual())
      and (select private.tiene_rol(array['administrador']::public.rol_usuario[]))
    )
  );

revoke all on public.aperturas_remotas from anon, authenticated;
grant select on public.aperturas_remotas to authenticated;
grant all on public.aperturas_remotas to service_role;

create function private.aperturas_recientes(p_user_id uuid, p_segundos int)
returns int
language sql
stable
security definer
set search_path = ''
as $$
  select count(*)::int
  from public.aperturas_remotas a
  where a.user_id = p_user_id
    and a.created_at > now() - make_interval(secs => p_segundos);
$$;

revoke execute on function private.aperturas_recientes(uuid, int) from public, anon, authenticated;
grant execute on function private.aperturas_recientes(uuid, int) to service_role;

-- estado_app_domicilio -----------------------------------------------------------------

create function public.estado_app_domicilio(p_domicilio_id bigint)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_dom record;
  v_moroso boolean;
  v_puede boolean;
begin
  if not coalesce(private.es_residente_de(p_domicilio_id), false) then
    raise exception 'No autorizado' using errcode = '42501';
  end if;

  select d.id, d.direccion, d.titular_id, f.id as fraccionamiento_id, f.nombre, f.instalacion_id
    into v_dom
  from public.domicilios d
  join public.fraccionamientos f on f.id = d.fraccionamiento_id
  where d.id = p_domicilio_id;

  v_moroso := coalesce(private.moroso_efectivo(p_domicilio_id), false);
  v_puede := not v_moroso and v_dom.instalacion_id is not null and v_dom.titular_id is not null;

  return jsonb_build_object(
    'domicilio', jsonb_build_object('id', v_dom.id, 'direccion', v_dom.direccion),
    'fraccionamiento', jsonb_build_object('nombre', v_dom.nombre),
    'moroso', v_moroso,
    'pin', (select p.pin from public.pines_acceso p where p.domicilio_id = p_domicilio_id),
    'botones', coalesce((
      select jsonb_agg(jsonb_build_object(
               'id', b.id,
               'orden', b.orden,
               'nombre', b.nombre,
               'icono', b.icono,
               'ancho_completo', b.ancho_completo,
               'habilitado', v_puede and b.salida_id is not null
             ) order by b.orden)
      from public.app_botones b
      where b.fraccionamiento_id = v_dom.fraccionamiento_id
    ), '[]'::jsonb)
  );
end;
$$;

revoke execute on function public.estado_app_domicilio(bigint) from public, anon;
grant execute on function public.estado_app_domicilio(bigint) to authenticated, service_role;
