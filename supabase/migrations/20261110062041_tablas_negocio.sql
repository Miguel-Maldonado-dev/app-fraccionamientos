create table public.domicilios (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  fraccionamiento_id bigint not null default private.fraccionamiento_actual() references public.fraccionamientos (id),
  direccion text not null,
  fecha_alta date not null,
  observaciones text,
  created_by uuid not null references public.perfiles (id),
  constraint domicilios_fraccionamiento_direccion_key unique (fraccionamiento_id, direccion),
  constraint domicilios_id_fraccionamiento_key unique (id, fraccionamiento_id)
);
alter table public.domicilios enable row level security;
create index domicilios_fraccionamiento_id_idx on public.domicilios (fraccionamiento_id);

create table public.conceptos_pago (
